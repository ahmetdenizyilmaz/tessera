import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 1400, height: 1000 } });
const page = await context.newPage();
const base = process.argv[2] ?? 'http://127.0.0.1:1420', errors = [];
context.on('page', child => child.on('pageerror', error => { if (!error.message.includes('WebSocket closed')) errors.push(error.message); }));
page.on('pageerror', error => { if (!error.message.includes('WebSocket closed')) errors.push(error.message); });
const manager = () => page.getByRole('dialog', { name: 'Manage add-ons', exact: true });
const openManager = async () => {
  await page.evaluate(() => window.creation.openNewSessionWizard());
  await page.getByRole('button', { name: 'Manage add-ons', exact: true }).click();
  await expect(manager()).toBeVisible();
};
try {
  await page.goto(`${base}/tools/window-fixture.html?addons`, { waitUntil: 'domcontentloaded' });
  await expect(page.locator('.tab-item')).toHaveCount(3);
  await page.evaluate(() => {
    window.appName = window.plugins.getState().addWebApp({ name: 'Test player', url: 'https://player.test', icon: 'Music' });
    window.creation.createPluginPanel(window.appName);
    window.mainPlayer = window.layout.getState().activeTabId;
    window.creation.createPluginPanel(window.appName, window.group);
    window.groupPlayer = [...window.plugins.getState().instances.values()].filter(instance => instance.pluginName === window.appName).at(-1).id;
    window.creation.createPluginPanel(window.appName);
    window.detachedPlayer = window.layout.getState().activeTabId;
  });
  const popupPromise = page.waitForEvent('popup');
  await page.evaluate(() => window.windows.detachPanel(window.detachedPlayer));
  const child = await popupPromise;
  await expect(child.locator('.detached-tab')).toHaveCount(1);
  const appName = await page.evaluate(() => window.appName);
  const snapshot = await page.evaluate(() => window.serializeWorkspace());
  await openManager();
  await manager().getByRole('button', { name: 'Remove Test player', exact: true }).click();
  await expect(manager()).toContainText('This will close 3 open panels.');
  await manager().getByRole('button', { name: 'Cancel', exact: true }).click();
  expect(await page.evaluate(name => [...window.plugins.getState().instances.values()].filter(p => p.pluginName === name).length, appName)).toBe(3);
  await manager().getByRole('button', { name: 'Remove Test player', exact: true }).click();
  await manager().getByRole('button', { name: 'Confirm removal of Test player', exact: true }).click();
  await expect.poll(() => page.evaluate(name => [...window.plugins.getState().instances.values()].filter(p => p.pluginName === name).length, appName)).toBe(0);
  await expect.poll(() => child.isClosed()).toBe(true);
  expect(await page.evaluate(() => window.groups.getState().groups.get(window.group).childIds.includes(window.groupPlayer))).toBe(false);
  expect(await page.evaluate(() => [window.lichess, window.timer].every(id => window.plugins.getState().instances.has(id)))).toBe(true);
  await expect.poll(() => page.evaluate(() => [window.mainPlayer, window.groupPlayer, window.detachedPlayer].every(id => window.calls.some(call => call.command === 'browser_panel_close' && call.args.id === id)))).toBe(true);
  await expect(page.locator('.nsw-more').getByRole('button', { name: 'Test player', exact: true })).toHaveCount(0);
  await page.screenshot({ path: '../tessera-office-validation/addon-manager.png' });
  await manager().getByRole('button', { name: 'Close add-on manager' }).click();
  await page.getByRole('button', { name: 'Plugins', exact: true }).click();
  await expect(page.locator('.menu-dropdown').getByRole('button', { name: 'Test player', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Manage add-ons…', exact: true }).click();
  await expect(manager()).toBeVisible(); await page.keyboard.press('Escape');
  console.log('PASS removal confirmation/cancel, all copies closed across main/group/detached window, native cleanup, unrelated panels preserved, and launch menus updated');

  await page.reload(); await expect(page.locator('.tab-item')).toHaveCount(3);
  await page.evaluate(saved => window.deserializeWorkspace(saved), snapshot);
  expect(await page.evaluate(name => [...window.plugins.getState().instances.values()].some(p => p.pluginName === name), appName)).toBe(false);
  expect(await page.evaluate(name => window.plugins.getState().removedPlugins.has(name), appName)).toBe(true);
  await openManager();
  await manager().locator('summary').click();
  await manager().getByRole('button', { name: 'Restore Test player', exact: true }).click();
  await manager().getByRole('button', { name: 'Close add-on manager' }).click();
  await page.locator('.nsw-more').getByRole('button', { name: 'Test player', exact: true }).click();
  expect(await page.evaluate(name => window.plugins.getState().registry.get(name).browserSite, appName)).toBe(appName);
  expect(await page.evaluate(name => window.calls.findLast(call => call.command === 'browser_panel_create' && call.args.site === name)?.args.homeUrl, appName)).toBe('https://player.test/');
  console.log('PASS removal survives restart and old-workspace restore; restoring the add-on keeps its native cookie profile');

  await openManager();
  await manager().getByRole('button', { name: 'Remove Timer', exact: true }).click();
  await manager().getByRole('button', { name: 'Confirm removal of Timer', exact: true }).click();
  await expect.poll(() => page.evaluate(() => [...window.plugins.getState().instances.values()].some(p => p.pluginName === 'timer'))).toBe(false);
  await manager().getByRole('button', { name: 'Close add-on manager' }).click();
  await page.getByRole('button', { name: 'Plugins', exact: true }).click();
  await expect(page.locator('.menu-dropdown').getByRole('button', { name: 'Timer', exact: true })).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.reload();
  await expect(page.locator('.tab-item')).toHaveCount(2);
  await page.getByRole('button', { name: 'Lichess view settings', exact: true }).click();
  await page.getByRole('button', { name: 'Remove web player…', exact: true }).click();
  await expect(manager().getByRole('button', { name: 'Confirm removal of Lichess', exact: true })).toBeVisible();
  await manager().getByRole('button', { name: 'Confirm removal of Lichess', exact: true }).click();
  await expect(manager()).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => [...window.plugins.getState().instances.values()].some(p => p.pluginName === 'lichess'))).toBe(false);
  await openManager();
  await page.setViewportSize({ width: 600, height: 650 });
  const bounds = await manager().boundingBox();
  expect(bounds.x).toBeGreaterThanOrEqual(0); expect(bounds.x + bounds.width).toBeLessThanOrEqual(600);
  expect(bounds.y).toBeGreaterThanOrEqual(0); expect(bounds.y + bounds.height).toBeLessThanOrEqual(650);
  await page.screenshot({ path: '../tessera-office-validation/addon-manager-narrow.png' });
  await manager().locator('summary').click();
  await manager().getByRole('button', { name: 'Restore Lichess', exact: true }).click();
  expect(await page.evaluate(() => window.plugins.getState().registry.get('lichess').browserSite)).toBe('lichess');
  expect(errors).toEqual([]);
  console.log('PASS built-in plugin removal persists, direct web-panel removal, restoration, and narrow-window dialog');
} finally { await browser.close(); }
